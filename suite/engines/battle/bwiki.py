"""bwiki.py - BWIKI (洛克王国:手游WIKI) battle knowledge accessor.

Primary battle data source for the battle engine.  It is imported from
`datasets/bwiki/bwiki_battle.db`, generated by `.tmp/bwiki_import2.py` out of the
wiki's own Lua data modules:

    模块:PetData/SkillCatalog   788 skills (name/element/category/energy/power/target/desc)
    模块:PetData/Core           596 pets (types, base stats, feature skill, evolution group)
    模块:PetData/LearnsetCatalog learnsets (learn nodes with level, 18 bloodline nodes, stone skills)
    模块:PetData/Evolution      242 evolution chains
    Widget:RestrainCalc         official type-effectiveness chart

`nrc.db` stays available as a fallback / legacy table; bwiki wins whenever a name
resolves here, because it carries the full 788-skill catalogue versus nrc.db's 491
rows and the community-maintained type chart.

Everything here is read-only: connections open with `mode=ro&immutable=1`.
"""
from __future__ import annotations

import difflib
import os
import sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
SUITE = os.path.dirname(os.path.dirname(HERE))  # .../rocogi/suite
ROOT = os.path.dirname(SUITE)  # .../rocogi
DEFAULT_DB = os.path.join(ROOT, "datasets", "bwiki", "bwiki_battle.db")

DB_PATH = DEFAULT_DB


def bind(path: str | None = None) -> str:
    """Point the accessor at a specific db file (config override) and return it."""
    global DB_PATH
    if path:
        DB_PATH = os.path.normpath(path)
    return DB_PATH


def available() -> bool:
    return os.path.exists(DB_PATH)


def connect() -> sqlite3.Connection:
    con = sqlite3.connect(f"file:{DB_PATH}?mode=ro&immutable=1", uri=True)
    con.row_factory = sqlite3.Row
    return con


def _rows(con, sql, params=()):
    return [dict(r) for r in con.execute(sql, params)]


def _is_subsequence(short: str, long: str) -> bool:
    it = iter(long)
    return all(ch in it for ch in short)


def _fuzzy(con, table: str, columns, name, cutoff: float = 0.62, limit: int = 3):
    """Last-resort name match for OCR output and typos.

    WinRT OCR mangles hand-drawn CJK names: `音波` still resolves through the LIKE
    prefix, but `水枪` does not resolve against the real `水弹枪`.  Individual
    characters survive OCR far better than their exact sequence, so a subsequence
    hit is trusted above plain string similarity.
    """
    needle = str(name or "").strip()
    if not needle:
        return []
    scored = []
    for row in con.execute(f"SELECT * FROM {table}"):
        best, how = 0.0, ""
        for column in columns:
            cand = row[column]
            if not cand:
                continue
            cand = str(cand)
            ratio = difflib.SequenceMatcher(None, needle, cand).ratio()
            if ratio >= 0.4 and (_is_subsequence(needle, cand) or _is_subsequence(cand, needle)):
                score, kind = min(1.0, ratio + 0.35), "subsequence"
            else:
                score, kind = ratio, "ratio"
            if score > best:
                best, how = score, kind
        if best >= cutoff:
            record = dict(row)
            record["_match"] = how
            record["_score"] = round(best, 3)
            scored.append(record)
    scored.sort(key=lambda r: -r["_score"])
    return scored[:limit]


def summary() -> dict:
    if not available():
        return {"available": False, "db": DB_PATH}
    with connect() as con:
        counts = {t: con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
                  for t in ("skill", "pet", "pet_skill", "type_chart", "evolution")}
        meta = {r["key"]: r["value"] for r in con.execute("SELECT key, value FROM meta")}
    return {"available": True, "db": os.path.relpath(DB_PATH, ROOT), "counts": counts,
            "source": meta.get("source"), "fetched_at": meta.get("fetched_at"),
            "license": meta.get("license")}


def find_pet(name: str):
    """Exact match first, then title/partial, then a fuzzy last resort."""
    needle = str(name or "").strip()
    if not needle:
        return []
    with connect() as con:
        rows = _rows(con, "SELECT * FROM pet WHERE name = ? OR title = ? OR name LIKE ? "
                          "ORDER BY (name = ? OR title = ?) DESC, length(name)",
                     (needle, needle, f"%{needle}%", needle, needle))
        if not rows:
            rows = _fuzzy(con, "pet", ("name", "title"), needle)
    return rows


def find_skill(name: str):
    """Exact match first, then partial, then a fuzzy last resort (OCR mangling)."""
    needle = str(name or "").strip()
    if not needle:
        return []
    with connect() as con:
        rows = _rows(con, "SELECT * FROM skill WHERE name = ? OR name LIKE ? "
                          "ORDER BY (name = ?) DESC, length(name)",
                     (needle, f"%{needle}%", needle))
        if not rows:
            rows = _fuzzy(con, "skill", ("name",), needle)
    return rows


def pet_skills(pet_name: str, kinds=("learn", "bloodline", "stone")):
    marks = ",".join("?" * len(kinds))
    sql = ("SELECT ps.* FROM pet_skill ps JOIN pet p ON p.pet_id = ps.pet_id "
           f"WHERE (p.name = ? OR p.title = ?) AND ps.kind IN ({marks}) ORDER BY ps.kind, ps.level")
    with connect() as con:
        return _rows(con, sql, (pet_name, pet_name, *kinds))


def type_multiplier(atk_element: str, def_types) -> float:
    """Product of the wiki's chart over every defender type (dual typing stacks)."""
    if not def_types:
        return 1.0
    atk = atk_element[:-1] if atk_element.endswith("系") else atk_element
    mult = 1.0
    with connect() as con:
        for dfn in def_types:
            d = dfn[:-1] if dfn.endswith("系") else dfn
            row = con.execute("SELECT multiplier FROM type_chart WHERE atk = ? AND def = ?",
                              (atk, d)).fetchone()
            if row:
                mult *= float(row["multiplier"])
    return mult


def best_skill(pet_name: str, enemy_types=(), energy: int | None = None, kinds=("learn", "bloodline", "stone")):
    """Rank the pet's attacking skills by effective damage per energy.

    score = power * type_multiplier / max(energy, 1)  -- sustained damage; the raw
    power*mult product is reported too so a single big hit can be recognised.
    """
    rows = pet_skills(pet_name, kinds)
    ranked = []
    for r in rows:
        if r["category"] != "攻击" or not r["power"]:
            continue
        if energy is not None and (r["energy"] or 0) > energy:
            continue
        mult = type_multiplier(r["element"], enemy_types)
        eff = float(r["power"]) * mult
        ranked.append({
            "name": r["skill_name"], "skill": r["skill_name"],
            "element": r["element"], "power": r["power"],
            "energy": r["energy"], "damage_class": r["damage_class"], "kind": r["kind"],
            "level": r["level"], "multiplier": round(mult, 3),
            "effective_power": round(eff, 1),
            "score": round(eff / max(int(r["energy"] or 1), 1), 2),
        })
    ranked.sort(key=lambda x: (-x["score"], -x["effective_power"]))
    return ranked


def type_chart(atk_element: str | None = None):
    sql = "SELECT atk, def, multiplier FROM type_chart"
    params = ()
    if atk_element:
        atk = atk_element[:-1] if atk_element.endswith("系") else atk_element
        sql += " WHERE atk = ?"
        params = (atk,)
    with connect() as con:
        return _rows(con, sql + " ORDER BY atk, multiplier DESC", params)


def relations(atk_element: str) -> dict:
    """Four-way split exactly like the wiki calculator: strong/resist/weak/vulnerable."""
    atk = atk_element[:-1] if atk_element.endswith("系") else atk_element
    out = {"strong": [], "resist": [], "neutral": []}
    with connect() as con:
        for r in con.execute("SELECT def, multiplier FROM type_chart WHERE atk = ?", (atk,)):
            out["strong" if float(r["multiplier"]) > 1 else "resist"].append(r["def"])
        for r in con.execute("SELECT DISTINCT def FROM type_chart"):
            d = r["def"]
            if d in out["strong"] or d in out["resist"]:
                continue
            hit = con.execute("SELECT 1 FROM type_chart WHERE atk = ? AND def = ?", (atk, d)).fetchone()
            if not hit:
                out["neutral"].append(d)
    return out


def evolution_chain(pet_name: str):
    with connect() as con:
        pet = con.execute("SELECT pet_id, evolution_groups FROM pet WHERE name = ? OR title = ?",
                          (pet_name, pet_name)).fetchone()
        if not pet or not pet["evolution_groups"]:
            return []
        group = pet["evolution_groups"].split(",")[0]
        nodes = _rows(con, "SELECT * FROM evolution WHERE group_key = ? ORDER BY ord", (group,))
    return nodes
